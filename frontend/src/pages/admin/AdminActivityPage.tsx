import { useState } from 'react'
import { AdminActivityList } from '../../components/admin/AdminActivityList'
import { PageHeader } from '../../components/common/PageHeader'
import { Card } from '../../components/ui/Card'
import { FilterChip } from '../../components/ui/FilterChip'
import { SearchBar } from '../../components/ui/SearchBar'
import { useDemoCatalog } from '../../context/catalogStore'
import type { AdminActivityArea } from '../../types/admin'

const areaFilters: Array<{ value: AdminActivityArea | 'all'; label: string }> = [
  { value: 'all', label: 'All activity' },
  { value: 'hospital', label: 'Hospitals' },
  { value: 'doctor', label: 'Doctors' },
  { value: 'appointment', label: 'Appointments' },
  { value: 'insurance', label: 'Insurance' },
  { value: 'patient', label: 'Patients' },
  { value: 'system', label: 'System' },
]

export function AdminActivityPage() {
  const { activity } = useDemoCatalog()
  const [areaFilter, setAreaFilter] = useState<AdminActivityArea | 'all'>('all')
  const [search, setSearch] = useState('')

  const query = search.trim().toLowerCase()
  const filtered = activity.filter((entry) => {
    if (areaFilter !== 'all' && entry.area !== areaFilter) return false
    if (!query) return true
    return `${entry.title} ${entry.detail}`.toLowerCase().includes(query)
  })

  return (
    <div>
      <PageHeader
        eyebrow="Admin · Activity"
        title="Activity log"
        description="A local record of demo admin changes. Entries are simulated and stored only in this browser."
      />

      <Card className="bg-white">
        <SearchBar
          value={search}
          onChange={setSearch}
          label="Search activity"
          placeholder="Search activity titles or details"
        />
        <div className="mt-3 flex flex-wrap gap-2">
          {areaFilters.map((filter) => (
            <FilterChip
              key={filter.value}
              active={areaFilter === filter.value}
              onClick={() => setAreaFilter(filter.value)}
            >
              {filter.label}
            </FilterChip>
          ))}
        </div>
      </Card>

      <div className="mt-4 flex items-center justify-between gap-2">
        <p className="text-xs text-brand-navy-soft">
          Showing <span className="font-semibold text-brand-navy">{filtered.length}</span> of{' '}
          {activity.length} entries.
        </p>
        <span className="text-[11px] text-brand-navy-soft/70">Keeps the latest 200 actions</span>
      </div>

      <Card className="mt-3 bg-white">
        <AdminActivityList
          activity={filtered}
          emptyMessage="No activity matches those filters yet."
        />
      </Card>

      <p className="mt-4 text-[11px] leading-relaxed text-brand-navy-soft">
        Activity entries are generated by actions in this demo admin console, such as editing a
        hospital, activating a doctor, or cancelling an appointment. Nothing is sent to a server.
      </p>
    </div>
  )
}
