/** Hospitals ordered by simulated distance from the selected demo location. */
export function getHospitalsForLocationFrom(
  hospitals: Hospital[],
  locationId: string,
): Hospital[] {
  const distances = hospitalDistanceKmByLocation[locationId] ?? {}
  const location = demoLocations.find((item) => item.id === locationId)

  return hospitals
    .map((hospital) => {
      const explicit = distances[hospital.id]
      const estimated =
        explicit ??
        (location && hospital.coordinates
          ? Math.round(
              distanceInKilometers(location.coordinates, hospital.coordinates) * 10,
            ) / 10
          : undefined)

      return {
        ...hospital,
        distanceKm: estimated ?? hospital.distanceKm,
      }
    })
    .sort((a, b) => a.distanceKm - b.distanceKm)
}

export function getHospitalsForLocation(locationId: string): Hospital[] {
  return getHospitalsForLocationFrom(demoHospitals, locationId)
}
